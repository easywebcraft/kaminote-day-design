  var LANGS = { ja: 'ja', en: 'en', pt: 'pt-BR', tl: 'tl', ceb: 'ceb' };

  function mark(lang) {
    document.documentElement.setAttribute('lang', LANGS[lang] || 'ja');
    // 選んでいる言語に印を付ける（3つ並べる古い形と、ボタン＋一覧の新しい形の両方）
    document.querySelectorAll('.lang button[data-lang]').forEach(function (b) {
      var on = b.getAttribute('data-lang') === lang;
      b.classList.toggle('on', on);
      b.setAttribute('aria-pressed', on ? 'true' : 'false');
      if (b.closest('.lang-menu')) { b.setAttribute('aria-current', on ? 'true' : 'false'); }
    });
    try { localStorage.setItem('kaminote-lang', lang); } catch (e) {}
  }

  function apply(lang) {
    var d = DICT[lang];
    if (d) {
      document.querySelectorAll('[data-i18n]').forEach(function (el) {
        var t = d[el.getAttribute('data-i18n')];
        if (t !== undefined) { el.innerHTML = t; }
      });
    }
    mark(lang);
  }

  // ---- ボタンを押すと一覧が出る形（言語を増やしてもボタンは1つのまま） ----
  function menu() { return document.querySelector('.lang-menu'); }
  function toggle(open) {
    var m = menu(), b = document.querySelector('.lang-btn');
    if (!m || !b) { return; }
    m.hidden = !open;
    b.setAttribute('aria-expanded', open ? 'true' : 'false');
    // スマホのメニューが開いていたら閉じる（同じ場所に2枚重なるのを防ぐ）
    if (open) {
      var head = document.querySelector('.head');
      if (head) { head.classList.remove('open'); }
      var burger = document.querySelector('.burger');
      if (burger) { burger.setAttribute('aria-expanded', 'false'); }
    }
  }

  function boot() {
    var saved = null;
    try { saved = localStorage.getItem('kaminote-lang'); } catch (e) {}
    // 日本語のときは書き換えない（もとのHTMLがそのまま日本語なので、触るだけ無駄）
    if (saved && saved !== 'ja' && DICT[saved]) { apply(saved); } else { mark('ja'); }

    document.addEventListener('click', function (e) {
      var t = e.target;
      if (!t || !t.closest) { return; }
      var opt = t.closest('.lang button[data-lang]');
      if (opt) { apply(opt.getAttribute('data-lang')); toggle(false); return; }
      if (t.closest('.lang-btn')) {
        var m = menu();
        toggle(!m || m.hidden);
        e.stopPropagation();
        return;
      }
      // 外side を押したら閉じる
      if (!t.closest('.lang')) { toggle(false); }
    });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') { toggle(false); }
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else { boot(); }
